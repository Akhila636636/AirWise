const translations: Record<Language, TranslationDict> = { en, hi, te };

/**
 * Get a translation string for the given key and language.
 * Falls back to English if key is missing in the target language.
 */
export function t(key: string, language: Language = 'en'): string {
  return translations[language][key] ?? translations.en[key] ?? key;
}

/**
 * Get all translation keys that exist in the English dictionary
 */
export function getTranslationKeys(): readonly string[] {
  return Object.keys(translations.en);
}
